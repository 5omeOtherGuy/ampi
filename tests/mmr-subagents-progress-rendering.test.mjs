const UPDATE_FIXTURES = process.env.PI_MMR_UPDATE_FIXTURES === "1";
const ROW_FIXTURE_DIR = path.resolve(import.meta.dirname, "fixtures/mmr-subagents-worker-rows");
const ROW_CWD = "/work/repo";

function assertRowFixture(filename, actual) {
  const fixturePath = path.join(ROW_FIXTURE_DIR, filename);
  if (UPDATE_FIXTURES || !existsSync(fixturePath)) {
    mkdirSync(ROW_FIXTURE_DIR, { recursive: true });
    writeFileSync(fixturePath, actual);
    return;
  }
  assert.equal(actual, readFileSync(fixturePath, "utf8"), `fixture ${filename} drift; rerun with PI_MMR_UPDATE_FIXTURES=1 to refresh`);
}

/** The renderers a worker tool registers, as Pi draws them with `renderShell: "self"`. */
function workerRenderers(renderers, toolName) {
  return {
    name: toolName,
    renderShell: "self",
    renderCall: (args, theme, context) => renderers.renderMmrSubagentCall(toolName, args, theme, context),
    renderResult: (result, options, theme, context) => renderers.renderMmrSubagentResult(toolName, result, options, theme, context),
  };
}

/** Pi's tool row for one worker call after its lifecycle: arguments complete, execution started, then an optional result. */
function workerRow(renderers, toolName, args, { result, isPartial = false, expanded = false } = {}) {
  const component = new ToolExecutionComponent(toolName, `${toolName}-1`, args, { showImages: false }, workerRenderers(renderers, toolName), noopTui, ROW_CWD);
  component.setExpanded(expanded);
  component.setArgsComplete();
  component.markExecutionStarted();
  if (result) component.updateResult(result, isPartial);
  return component;
}

